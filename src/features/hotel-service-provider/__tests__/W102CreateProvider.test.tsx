import { beforeEach, describe, expect, it, vi } from 'vitest';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { CreateServiceProviderView } from '../components/w102/CreateServiceProviderView';
import { ToastProvider } from '../components/common/Toast';
import { StaffProviderService } from '../services/staffProviderService';
vi.mock('next/navigation', () => ({ useRouter: () => ({ push: vi.fn() }) }));
vi.mock('../services/staffProviderService', () => ({ StaffProviderService: { fetchCommercialPois: vi.fn(), createServiceProviderAccount: vi.fn() } }));
beforeEach(() => { vi.resetAllMocks(); vi.mocked(StaffProviderService.fetchCommercialPois).mockResolvedValue([{ id: 2, name: 'Riverside Hotel', category: 'Hotel' }]); });
describe('UC77 provisioning', () => {
  it('requires explicit POI selection and sends exact account fields', async () => {
    vi.mocked(StaffProviderService.createServiceProviderAccount).mockResolvedValue({ success: true, account: { userId: 8, fullName: 'Name', email: 'name@example.com', phoneNumber: '0905123456', role: 'ServiceProvider', status: 'Active', mustChangePassword: true, linkedPoiIds: [2], emailDeliveryStatus: 'DefiniteFailure' } });
    render(<ToastProvider><CreateServiceProviderView /></ToastProvider>);
    await screen.findByRole('checkbox', { name: 'Select Riverside Hotel' });
    expect(screen.getByLabelText(/Business \/ Property Name/i).getAttribute('maxlength')).toBe('150');
    expect(screen.getByLabelText(/Representative Full Name/i).getAttribute('maxlength')).toBe('150');
    expect(screen.getByLabelText(/Account Email Address/i).getAttribute('maxlength')).toBe('200');
    expect(screen.getByLabelText(/Contact Phone Number/i).getAttribute('maxlength')).toBe('20');
    fireEvent.change(screen.getByLabelText(/Business \/ Property Name/i), { target: { value: 'Business' } });
    fireEvent.change(screen.getByLabelText(/Representative Full Name/i), { target: { value: 'Name' } });
    fireEvent.change(screen.getByLabelText(/Account Email Address/i), { target: { value: 'name@example.com' } });
    fireEvent.change(screen.getByLabelText(/Contact Phone Number/i), { target: { value: '0905123456' } });
    const submit = screen.getByRole('button', { name: /Create Provider Account/i });
    fireEvent.click(submit);
    expect(StaffProviderService.createServiceProviderAccount).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('checkbox', { name: 'Select Riverside Hotel' }));
    fireEvent.click(submit);
    await waitFor(() => expect(StaffProviderService.createServiceProviderAccount).toHaveBeenCalledWith({ fullName: 'Name', email: 'name@example.com', phoneNumber: '0905123456', businessName: 'Business', category: 'Hotel', linkedPoiIds: [2] }));
    expect(await screen.findByText(/account was created, but.*could not be sent/i)).toBeDefined();
    expect(screen.queryByLabelText(/password/i)).toBeNull();
  });
});
