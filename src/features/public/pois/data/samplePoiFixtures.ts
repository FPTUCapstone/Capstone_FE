export function getSamplePagedPois(query?: URLSearchParams): PagedPois {
  let items = [...SAMPLE_POIS];

  if (query) {
    const search = query.get('search')?.toLowerCase().trim();
    if (search) {
      items = items.filter(
        (poi) =>
          poi.name.toLowerCase().includes(search) ||
          (poi.address && poi.address.toLowerCase().includes(search)) ||
          poi.categoryName.toLowerCase().includes(search),
      );
    }

    const categoryId = query.get('categoryId');
    if (categoryId && categoryId !== '0') {
      const catNum = Number(categoryId);
      items = items.filter((poi) => poi.categoryId === catNum);
    }

    const openNow = query.get('openNow');
    if (openNow === 'true') {
      items = items.filter((poi) => poi.isOpenNow);
    }

    const sort = query.get('sort');
    if (sort === 'rating') {
      items.sort((a, b) => (b.averageRating ?? 0) - (a.averageRating ?? 0));
    } else if (sort === 'distance') {
      items.sort((a, b) => (a.distanceKm ?? 999) - (b.distanceKm ?? 999));
    } else if (sort === 'name') {
      items.sort((a, b) => a.name.localeCompare(b.name, 'vi'));
    }
  }

  const page = Math.max(1, Number(query?.get('page') ?? 1));
  const pageSize = 20;
  const totalCount = items.length;
  const totalPages = Math.ceil(totalCount / pageSize) || 1;
  const startIndex = (page - 1) * pageSize;
  const pageItems = items.slice(startIndex, startIndex + pageSize);

  return {
    page,
    pageSize,
    totalCount,
    totalPages,
    items: pageItems,
  };
}

