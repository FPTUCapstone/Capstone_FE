import { act, cleanup, renderHook, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import type { ChatGroupConversation } from '../services/chatGroupApi';
const api = vi.hoisted(() => ({ groups: vi.fn(), direct: vi.fn(), chatGroups: vi.fn(), history: vi.fn(), chatHistory: vi.fn(), post: vi.fn(), chatPost: vi.fn(), read: vi.fn(), chatRead: vi.fn(), members: vi.fn(), vote: vi.fn() }));
vi.mock('../services/travelGroupApi', async original => ({ ...(await original<object>()), fetchGroupConversations: api.groups, fetchGroupMessages: api.history, postGroupMessage: api.post, markGroupRead: api.read, fetchChatMembers: api.members, votePollOption: api.vote }));
vi.mock('../services/directChatApi', async original => ({ ...(await original<object>()), fetchDirectConversations: api.direct }));
vi.mock('../services/chatGroupApi', async original => ({ ...(await original<object>()), fetchChatGroupConversations: api.chatGroups, fetchChatGroupMessages: api.chatHistory, sendChatGroupMessage: api.chatPost, markChatGroupRead: api.chatRead }));
vi.mock('../services/chatNotifications', () => ({ subscribeToChatChanges: () => () => undefined }));
import { chatGroupThread, groupThread, useMessenger } from '../components/useMessenger';
import { TravelGroupHttpError } from '../services/travelGroupApi';
const group = (id = 1): ChatGroupConversation => ({ groupId: id, groupName: `Friends ${id}`, memberCount: 2, hostUserId: 42, lastMessage: null, lastMessageAtUtc: null, unreadCount: 2 });
const message = (id = 1) => ({ messageId: id, groupId: 1, senderUserId: 43, senderName: 'Friend', content: `Hello ${id}`, createdAtUtc: '2026-11-24T00:00:00Z', clientMessageId: `nonce-${id}`, messageType: 'text' as const, readByCount: 0, isReadByMe: false, presentCount: 0, isPresentByMe: false, paidUserIds: [], pollVoteCounts: {}, myPollVoteOption: null });
beforeEach(() => {
  vi.resetAllMocks();
  api.groups.mockResolvedValue({ items: [], nextBeforeGroupId: null });
  api.direct.mockResolvedValue({ items: [], nextBeforeConversationId: null });
  api.chatGroups.mockResolvedValue({ items: [group()], nextBeforeGroupId: null });
  api.history.mockResolvedValue([]); api.chatHistory.mockResolvedValue([]); api.members.mockResolvedValue([]);
  api.chatRead.mockResolvedValue(undefined);
  vi.spyOn(document, 'hasFocus').mockReturnValue(true);
});
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('keeps colliding travel and independent group IDs isolated for history, drafts, sends and read cursors', async () => {
  api.groups.mockResolvedValue({ items: [{ ...group(), itineraryId: 4, itineraryTitle: null, itinerarySourceType: 'Manual', status: 'Active' }], nextBeforeGroupId: null });
  api.history.mockResolvedValue([message(1)]); api.chatHistory.mockResolvedValue([message(1)]);
  api.chatPost.mockResolvedValue({ ...message(2), senderUserId: 42 });
  const { result } = renderHook(() => useMessenger(42, 'Traveler'));
  await waitFor(() => { expect(result.current.loading).toBe(false); expect(result.current.loadingMessages).toBe(false); });
  expect(result.current.threads.map(t => t.key)).toEqual(['group:1', 'chat-group:1']);
  act(() => result.current.setDraft('Travel draft'));
  api.members.mockClear(); api.history.mockClear(); api.read.mockClear();
  act(() => result.current.openChatGroup(group()));
  await waitFor(() => expect(result.current.messages).toHaveLength(1));
  expect(result.current.selected?.group).toMatchObject({ itineraryId: 0, itineraryTitle: null, itinerarySourceType: 'Independent' });
  expect(result.current.draft).toBe('');
  expect(api.chatRead).toHaveBeenCalledWith(1, 1);
  expect(api.members).not.toHaveBeenCalled(); expect(api.history).not.toHaveBeenCalled(); expect(api.read).not.toHaveBeenCalled();
  await act(async () => { expect(await result.current.send('text', 'Hello 2')).toBe(true); });
  expect(api.chatPost).toHaveBeenCalledWith(1, 'Hello 2', expect.any(String)); expect(api.post).not.toHaveBeenCalled();
  act(() => result.current.select(result.current.threads.find(t => t.key === 'group:1')!));
  expect(result.current.draft).toBe('Travel draft');
  await waitFor(() => expect(result.current.loadingMessages).toBe(false));
});
it('tracks a third pagination frontier without resetting it on refresh', async () => {
  api.chatGroups.mockImplementation(async (before?: number) => ({ items: [group(before ? before - 1 : 3)], nextBeforeGroupId: before === 2 ? null : before ? 2 : 3 }));
  const { result } = renderHook(() => useMessenger(42, 'Traveler'));
  await waitFor(() => expect(result.current.loading).toBe(false));
  await act(async () => result.current.loadMoreThreads());
  await act(async () => result.current.refresh());
  api.groups.mockClear(); api.direct.mockClear(); api.chatGroups.mockClear();
  await act(async () => result.current.loadMoreThreads());
  expect(api.chatGroups).toHaveBeenCalledWith(2); expect(api.groups).not.toHaveBeenCalled(); expect(api.direct).not.toHaveBeenCalled();
  expect(result.current.threads.map(t => t.key)).toEqual(['chat-group:3', 'chat-group:2', 'chat-group:1']);
  expect(result.current.hasMoreThreads).toBe(false);
});
it('surfaces third API errors and recovers through refresh', async () => {
  api.chatGroups.mockRejectedValueOnce(new TravelGroupHttpError(503, 'Chat unavailable'));
  const { result } = renderHook(() => useMessenger(42, 'Traveler'));
  await waitFor(() => expect(result.current.listError).toBe('Chat unavailable'));
  await act(async () => result.current.refresh());
  expect(result.current.listError).toBeNull(); expect(result.current.selected?.chatGroup).toBe(true);
});
it('does not mark read while minimized, including a history response arriving after minimize', async () => {
  let resolve!: (rows: ReturnType<typeof message>[]) => void;
  api.chatHistory.mockReturnValueOnce(new Promise(r => { resolve = r; }));
  const { result, rerender } = renderHook(({ readable }) => useMessenger(42, 'Traveler', readable), { initialProps: { readable: true } });
  await waitFor(() => expect(result.current.selected?.key).toBe('chat-group:1'));
  rerender({ readable: false });
  await act(async () => resolve([message()]));
  expect(api.chatRead).not.toHaveBeenCalled(); expect(result.current.threads[0].unread).toBe(2);
  rerender({ readable: true });
  api.chatHistory.mockResolvedValue([message()]);
  await act(async () => result.current.select(chatGroupThread(group())));
  expect(api.chatRead).toHaveBeenCalledWith(1, 1);
});
it('reuses the send nonce on retry and refuses travel-tool sends and interactions', async () => {
  api.chatPost.mockRejectedValueOnce(new TravelGroupHttpError(503, 'Lost response')).mockResolvedValueOnce({ ...message(2), senderUserId: 42 });
  const { result } = renderHook(() => useMessenger(42, 'Traveler'));
  await waitFor(() => { expect(result.current.loading).toBe(false); expect(result.current.loadingMessages).toBe(false); });
  act(() => result.current.setDraft('Hello 2'));
  await act(async () => { expect(await result.current.send('text', 'Hello 2')).toBe(false); });
  expect(result.current.draft).toBe('Hello 2');
  await act(async () => { expect(await result.current.send('text', 'Hello 2')).toBe(true); });
  expect(api.chatPost.mock.calls[0][2]).toBe(api.chatPost.mock.calls[1][2]); expect(result.current.draft).toBe('');
  await act(async () => { expect(await result.current.send('poll', 'Question')).toBe(false); await result.current.interact(message(), 'vote', 0); });
  expect(api.chatPost).toHaveBeenCalledTimes(2); expect(api.post).not.toHaveBeenCalled(); expect(api.vote).not.toHaveBeenCalled();
});
it('ignores late independent history and sends after switching to a travel group with the same ID', async () => {
  let history!: (rows: ReturnType<typeof message>[]) => void;
  let sent!: (row: ReturnType<typeof message>) => void;
  api.chatHistory.mockReturnValueOnce(new Promise(resolve => { history = resolve; }));
  api.chatPost.mockReturnValueOnce(new Promise(resolve => { sent = resolve; }));
  const { result } = renderHook(() => useMessenger(42, 'Traveler'));
  await waitFor(() => expect(result.current.selected?.key).toBe('chat-group:1'));
  let sending!: Promise<boolean>;
  act(() => { sending = result.current.send('text', 'Hello 2'); });
  await act(async () => { expect(await result.current.send('text', 'Hello 2')).toBe(false); });
  expect(api.chatPost).toHaveBeenCalledTimes(1);
  act(() => result.current.select(groupThread({ ...group(), itineraryId: 4, itineraryTitle: null, itinerarySourceType: 'Manual', status: 'Active' })));
  await act(async () => { history([message()]); sent({ ...message(2), senderUserId: 42 }); await sending; });
  expect(result.current.selected?.key).toBe('group:1'); expect(result.current.messages).toEqual([]);
  expect(api.chatRead).not.toHaveBeenCalled();
});
